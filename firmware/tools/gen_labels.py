"""Generate src/labels.rs: the "PLATFORM n" bezel labels as 2-bit coverage
bitmaps of Helvetica Bold at a 13 px cap height, like the paint on the real
sign's bezel. Run on macOS: python3 -I tools/gen_labels.py > src/labels.rs
"""
from PIL import Image, ImageDraw, ImageFont

CAP = 13
FONT = "/System/Library/Fonts/Helvetica.ttc"


def font_for_cap(cap):
    for size in range(6, 60):
        f = ImageFont.truetype(FONT, size, index=1)  # index 1 = Bold
        l, t, r, b = f.getbbox("P")
        if b - t >= cap:
            return f
    raise SystemExit("no size")


def glyph(text):
    f = font_for_cap(CAP)
    l, t, r, b = f.getbbox(text)
    img = Image.new("L", (r - l + 4, b - t + 4), 0)
    ImageDraw.Draw(img).text((2 - l, 2 - t), text, font=f, fill=255)
    img = img.point(lambda v: min(3, (v + 42) // 85) * 85)
    return img.crop(img.getbbox())


print("//! Generated by tools/gen_labels.py: \"PLATFORM n\" in Helvetica Bold,")
print("//! 13 px cap height, 2 bits per pixel (0 = bezel .. 3 = paint), four")
print("//! pixels per byte, most significant bits first, rows byte-aligned.")
print()
print("pub struct Label {")
print("    pub width: usize,")
print("    pub height: usize,")
print("    pub data: &'static [u8],")
print("}")
print()
print("impl Label {")
print("    pub fn level(&self, x: usize, y: usize) -> u8 {")
print("        let stride = self.width.div_ceil(4);")
print("        (self.data[y * stride + x / 4] >> (6 - 2 * (x % 4))) & 3")
print("    }")
print("}")
print()
def emit(text):
    img = glyph(text)
    w, h = img.size
    px = img.load()
    data = []
    for y in range(h):
        for x0 in range(0, w, 4):
            byte = 0
            for k in range(4):
                v = px[x0 + k, y] // 85 if x0 + k < w else 0
                byte |= v << (6 - 2 * k)
            data.append(byte)
    print(f"    // {text}")
    print(f"    Label {{ width: {w}, height: {h}, data: &[")
    for i in range(0, len(data), 24):
        print("        " + " ".join(f"0x{b:02x}," for b in data[i:i + 24]))
    print("    } },".replace("} },", "] },"))


print("/// Index n is \"PLATFORM n\"; index 0 is unused.")
print("pub const PLATFORM: [Label; 10] = [")
for n in range(10):
    emit(f"PLATFORM {n}")
print("];")
print()
PAIRS = [(a, b) for a in range(1, 5) for b in range(a + 1, 5)]
print("/// Platform pairs (a < b), for a direction served by two platforms.")
print(f"pub const PAIRS: [(u8, u8); {len(PAIRS)}] = {PAIRS!r};".replace("[(", "[(").replace(")]", ")]"))
print()
print("/// \"PLATFORMS a & b\", in the order of [`PAIRS`].")
print(f"pub const PLATFORM_PAIRS: [Label; {len(PAIRS)}] = [")
for a, b in PAIRS:
    emit(f"PLATFORMS {a} & {b}")
print("];")
